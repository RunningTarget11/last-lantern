import {chromium,devices} from 'playwright';
const mode=process.argv[2]||'desktop';
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
const setups={desktop:{viewport:{width:1600,height:900}},landscape:{...devices['Pixel 7'],viewport:{width:915,height:412}},portrait:{...devices['Pixel 7']}};
const page=await (await browser.newContext(setups[mode])).newPage();const errs=[];
page.on('pageerror',e=>errs.push(e.message));page.on('console',m=>{if(m.type()==='error')errs.push(m.text());});
await page.goto('file:///workspace/last-lantern/index.html');await page.waitForFunction(()=>window.__LL,null,{timeout:180000});
await page.evaluate(()=>{const {G}=__LL;const s=G.sim;for(let i=0;i<60*20;i++){s.tick();G.world.handle(s.drainEvents());}});
await page.waitForTimeout(2500);await page.screenshot({path:`/tmp/sc_title_${mode}.jpg`,quality:85});
await page.click('#bPlay');await page.waitForTimeout(800);await page.screenshot({path:`/tmp/sc_levels_${mode}.jpg`,quality:85});
console.log(errs.join('\n'));await browser.close();
